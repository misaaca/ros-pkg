#!/usr/bin/env python3
"""
Regenerates Packages.toml, Packages.json, Packages.gz, kernel.toml, and SHA256SUMS
for the ROS GitHub Package Repository (https://github.com/misaaca/ros-pkg).

Called automatically by `ROS/scripts/publish_to_repo.sh`.
"""
import datetime
import gzip
import hashlib
import json
import os
import re
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(SCRIPT_DIR)
sys.path.insert(0, SCRIPT_DIR)

from build_rop import parse_rop_header_and_manifest

REPO_NAME = "ROS Official Package Repository (misaaca/ros-pkg)"
REPO_URL = "https://raw.githubusercontent.com/misaaca/ros-pkg/main"


def sha256_file(path: str) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(65536), b""):
            h.update(chunk)
    return h.hexdigest()


def find_latest_kernel():
    kdir = os.path.join(REPO_ROOT, "kernel")
    if not os.path.isdir(kdir):
        return None
    candidates = sorted(
        f for f in os.listdir(kdir)
        if f.startswith("ros_kernel-v") and os.path.isfile(os.path.join(kdir, f))
    )
    if not candidates:
        return None
    fname = candidates[-1]
    full = os.path.join(kdir, fname)
    m = re.match(r"ros_kernel-v([0-9.]+)-([a-zA-Z0-9_-]+)", fname)
    version = m.group(1) if m else "0.3.43"
    codename = m.group(2) if m else "rumi"
    digest = sha256_file(full)
    size = os.path.getsize(full)
    env_build = os.environ.get("ROS_BUILD_HEX", "").strip()
    build_hex = env_build if (env_build and env_build != "unknown") else digest[:8]
    return {
        "name": "ros_kernel",
        "version": version,
        "codename": codename,
        "build": build_hex,
        "arch": "x86_64",
        "filename": f"kernel/{fname}",
        "size": size,
        "sha256": digest,
        "release_date": datetime.datetime.now(datetime.timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ"),
        "changelog": f"ROS {version}-{codename} build {build_hex}",
    }


def scan_packages():
    pdir = os.path.join(REPO_ROOT, "packages")
    pkgs = []
    if not os.path.isdir(pdir):
        return pkgs
    for fname in sorted(os.listdir(pdir)):
        if not fname.endswith(".rop"):
            continue
        full = os.path.join(pdir, fname)
        raw = open(full, "rb").read()
        meta = parse_rop_header_and_manifest(raw)
        pkgs.append({
            "name": meta["name"] or fname[:-4],
            "version": meta["version"] or "1.0.0",
            "section": "utils",
            "arch": meta["arch"] or "x86_64",
            "description": meta["description"] or "ROS package",
            "dependencies": meta["dependencies"],
            "filename": f"packages/{fname}",
            "size": len(raw),
            "sha256": hashlib.sha256(raw).hexdigest(),
        })
    return pkgs


def main():
    kernel = find_latest_kernel()
    packages = scan_packages()

    toml_lines = [
        "# ROS Package Repository Index (auto-generated by tools/update_index.py)",
        "[repository]",
        f'name = "{REPO_NAME}"',
        f'url = "{REPO_URL}"',
        "",
    ]

    if kernel:
        toml_lines.extend([
            "[kernel]",
            f'name = "{kernel["name"]}"',
            f'version = "{kernel["version"]}"',
            f'codename = "{kernel["codename"]}"',
            f'build = "{kernel["build"]}"',
            f'arch = "{kernel["arch"]}"',
            f'filename = "{kernel["filename"]}"',
            f'size = {kernel["size"]}',
            f'sha256 = "{kernel["sha256"]}"',
            f'release_date = "{kernel["release_date"]}"',
            f'changelog = "{kernel["changelog"]}"',
            "",
        ])
        with open(os.path.join(REPO_ROOT, "kernel.toml"), "w", encoding="utf-8") as kf:
            kf.write("\n".join(toml_lines[5:]))

    for p in packages:
        deps = ", ".join(f'"{d}"' for d in p["dependencies"])
        toml_lines.extend([
            "[[package]]",
            f'name = "{p["name"]}"',
            f'version = "{p["version"]}"',
            f'section = "{p["section"]}"',
            f'arch = "{p["arch"]}"',
            f'description = "{p["description"]}"',
            f'dependencies = [{deps}]',
            f'filename = "{p["filename"]}"',
            f'size = {p["size"]}',
            f'sha256 = "{p["sha256"]}"',
            "",
        ])

    toml_text = "\n".join(toml_lines)
    with open(os.path.join(REPO_ROOT, "Packages.toml"), "w", encoding="utf-8") as f:
        f.write(toml_text)

    with gzip.open(os.path.join(REPO_ROOT, "Packages.gz"), "wb") as gz:
        gz.write(toml_text.encode("utf-8"))

    with open(os.path.join(REPO_ROOT, "Packages.json"), "w", encoding="utf-8") as jf:
        json.dump({"repository": {"name": REPO_NAME, "url": REPO_URL}, "kernel": kernel, "packages": packages}, jf, indent=2)

    sums = []
    if kernel:
        sums.append(f'{kernel["sha256"]}  {kernel["filename"]}')
    for p in packages:
        sums.append(f'{p["sha256"]}  {p["filename"]}')
    with open(os.path.join(REPO_ROOT, "SHA256SUMS"), "w", encoding="utf-8") as sf:
        sf.write("\n".join(sums) + ("\n" if sums else ""))

    print(f"[OK] Indexed kernel={'yes (' + kernel['version'] + '+' + kernel['build'] + ')' if kernel else 'none'}, packages={len(packages)}")


if __name__ == "__main__":
    main()
